# Tables to drop, in dependency order; an index disappears with its table.
TABLES_TO_DROP = ("search_rows", "model_rows", "runs")


def upgrade() -> None:
    saved = op.get_bind().exec_driver_sql("SELECT count(*) FROM runs").scalar()
    if saved:
        raise RuntimeError(FUSE_MESSAGE)
    for table in TABLES_TO_DROP:
        op.execute(f"DROP TABLE IF EXISTS {table} CASCADE")


def downgrade() -> None:
    for _name, statement in LEGACY_TABLES:
        op.execute(statement)
